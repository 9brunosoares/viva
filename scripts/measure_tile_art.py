"""Measure approved transparent sprites without modifying any image.

Uses the project's existing Pillow/NumPy tooling. Only the generated TS table
ships with the app; the detailed alpha audit stays in ignored test-results.
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TATTOOS = [
    "warrior", "books", "coffee", "lioness", "mother-infinity",
    "ionic-column", "outline-square",
]
fits = {}
audit = {}

for stage in range(1, 11):
    for kind in range(7 if stage == 9 else 6):
        key = f"{stage}-{kind}"
        name = f"tattoos/{TATTOOS[kind]}" if stage == 9 else f"tile-{key}"
        path = ROOT / "public/assets" / f"{name}.webp"
        with Image.open(path) as source:
            image = source.convert("RGBA")
        assert image.size == (160, 160), path
        alpha = np.asarray(image.getchannel("A"), dtype=float)
        bounds = image.getchannel("A").getbbox()
        assert bounds is not None, path
        x0, y0, x1, y1 = bounds
        ys, xs = np.indices(alpha.shape)
        mass = alpha.sum()
        # Preserve every extremity; alpha mass only nudges the optical center.
        cx = .8 * (x0 + x1) / 2 + .2 * float(((xs + .5) * alpha).sum() / mass)
        cy = .8 * (y0 + y1) / 2 + .2 * float(((ys + .5) * alpha).sum() / mass)
        extent = max(cx - x0, x1 - cx, cy - y0, y1 - cy)
        zoom = .88 * 160 / (2 * extent)
        x = (80 - cx) / 160 * zoom * 100
        y = (80 - cy) / 160 * zoom * 100
        fits[key] = [round(zoom, 6), round(x, 6), round(y, 6)]
        audit[key] = {
            "file": path.relative_to(ROOT).as_posix(), "bounds": bounds,
            "center": [cx, cy], "fit": fits[key],
        }

lines = [
    "// Generated by scripts/measure_tile_art.py from the original alpha, without editing assets.",
    "// [uniform scale, x%, y%]; 88% safe extent, 20% alpha-mass optical correction.",
    "export const tileArt: Readonly<Record<string, readonly [number, number, number]>> = {",
]
lines += [f'  "{key}": {json.dumps(value)},' for key, value in fits.items()]
lines += ["};", ""]
(ROOT / "src/tileArt.ts").write_text("\n".join(lines), encoding="utf-8")
folder = ROOT / "test-results/board-redesign"
folder.mkdir(parents=True, exist_ok=True)
(folder / "art-metrics.json").write_text(json.dumps(audit, indent=2), encoding="utf-8")
print(f"{len(fits)} measured sprites; originals unchanged")
