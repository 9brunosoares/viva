"""Extract existing wooden front lips; scene files remain byte-identical."""
from pathlib import Path
from PIL import Image,ImageDraw
import numpy as np
import json
root=Path(__file__).resolve().parents[1]
assets=root/'public/assets'
calibration=json.loads((root/'source-assets/shelf-contact/calibration.json').read_text())
# Other lips retain their original coordinates. Only the collectible shelf is calibrated.
planes=[[(235,246,454,236)],[(235,246,454,236)],[(235,346,454,341)],[(235,121,454,106),(235,267,454,260),(235,350,454,345)]]
for stage,edges in enumerate(planes):
 image=Image.open(assets/f'library-{stage}.webp').convert('RGBA')
 scale=4
 mask=Image.new('L',(image.width*scale,image.height*scale));draw=ImageDraw.Draw(mask)
 for x1,y1,x2,y2 in edges:draw.polygon([(x1*scale,y1*scale),(x2*scale,y2*scale),(x2*scale,(y2+7)*scale),(x1*scale,(y1+7)*scale)],fill=255)
 edge=[(x,y+calibration['frontOffset']) for x,y in calibration['surfaces'][stage]]
 polygon=edge+[(x,y+calibration['frontHeight']) for x,y in reversed(edge)]
 draw.polygon([(round(x*scale),round(y*scale)) for x,y in polygon],fill=255)
 mask=mask.resize(image.size,Image.Resampling.LANCZOS)
 image.putalpha(mask)
 image.save(assets/f'library-shelf-depth-{stage}.webp','WEBP',lossless=True,method=6)
metrics={}
for book in range(1,11):
 image=Image.open(assets/f'book-{book}-spine.webp').convert('RGBA')
 l,t,r,b=image.getchannel('A').getbbox()
 alpha=np.asarray(image.getchannel('A'))
 feet=[]
 for x in range(l+round((r-l)*.2),l+round((r-l)*.8)):
  ys=np.flatnonzero(alpha[:,x]>=200)
  if len(ys):feet.append((x+.5,float(ys[-1]+1)))
 contactY=float(np.percentile([y for x,y in feet],90))
 contactX=float(np.median([x for x,y in feet if y>=contactY-1]))
 metrics[book]=dict(width=image.width,height=image.height,left=l,top=t,artWidth=r-l,artHeight=b-t,contactX=contactX,contactY=contactY)
(root/'src/spineMetrics.ts').write_text('// Generated by scripts/prepare_shelf_depth.py. Contact uses the solid base, excluding the translucent fringe.\nexport const spineMetrics:Record<number,{width:number;height:number;left:number;top:number;artWidth:number;artHeight:number;contactX:number;contactY:number}>='+json.dumps(metrics)+';\n',encoding='utf-8')
(root/'src/shelfSurface.ts').write_text('// Generated from source-assets/shelf-contact/calibration.json; native 496 x 756 coordinates.\nexport const shelfSurfaces: readonly (readonly (readonly [number,number])[])[]='+json.dumps(calibration['surfaces'])+';\n',encoding='utf-8')
(assets/'shelf-depth.json').write_text(json.dumps(dict(otherPlanes=planes,calibration=calibration,spines=metrics),indent=2),encoding='utf-8')
print('Four original-wood lip overlays and ten non-destructive alpha-bound metrics generated.')
