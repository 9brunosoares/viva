"""Extract existing wooden front lips; scene files remain byte-identical."""
from pathlib import Path
from PIL import Image,ImageDraw
import json
root=Path(__file__).resolve().parents[1]
assets=root/'public/assets'
planes=[[(235,246,454,236)],[(235,183,454,173),(235,246,454,236)],[(235,188,454,176),(235,346,454,341)],[(235,121,454,106),(235,193,454,180),(235,267,454,260),(235,350,454,345)]]
for stage,edges in enumerate(planes):
 image=Image.open(assets/f'library-{stage}.webp').convert('RGBA')
 mask=Image.new('L',image.size);draw=ImageDraw.Draw(mask)
 for x1,y1,x2,y2 in edges:draw.polygon([(x1,y1),(x2,y2),(x2,y2+7),(x1,y1+7)],fill=255)
 image.putalpha(mask)
 image.save(assets/f'library-shelf-depth-{stage}.webp','WEBP',lossless=True,method=6)
metrics={}
for book in range(1,11):
 image=Image.open(assets/f'book-{book}-spine.webp').convert('RGBA')
 l,t,r,b=image.getchannel('A').getbbox()
 metrics[book]=dict(width=image.width,height=image.height,left=l,top=t,artWidth=r-l,artHeight=b-t)
(root/'src/spineMetrics.ts').write_text('// Generated by scripts/prepare_shelf_depth.py: transparent borders never determine shelf contact.\nexport const spineMetrics:Record<number,{width:number;height:number;left:number;top:number;artWidth:number;artHeight:number}>='+json.dumps(metrics)+';\n',encoding='utf-8')
(assets/'shelf-depth.json').write_text(json.dumps(dict(planes=planes,spines=metrics),indent=2),encoding='utf-8')
print('Four original-wood lip overlays and ten non-destructive alpha-bound metrics generated.')
